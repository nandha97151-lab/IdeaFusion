'use client';

import { useState, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  ArrowLeft, Bookmark, BookmarkCheck, Heart, Sparkles, Wrench,
  Copy, FileText, Share2, ChevronDown, ChevronUp, Zap,
  Target, Users, Lightbulb, Cpu, Award, FlaskConical, Eye, Download
} from 'lucide-react';
import { useAppStore } from '@/lib/store';
import { generateAlternatives, improveIdea, generateDevelopmentPlan, generatePrototype } from '@/lib/ai-service';
import type { AlternativeFusion, ImprovedIdea, DevelopmentPlan, PrototypeView } from '@/lib/ai-service';
import { ScoreRing, ScoreBar, OverallScore } from './ScoreVisuals';

export default function ResultPage() {
  const { currentResult, setCurrentView, addSavedIdea, toggleFavorite, savedIdeas } = useAppStore();

  const [alternatives, setAlternatives] = useState<AlternativeFusion[]>([]);
  const [improved, setImproved] = useState<ImprovedIdea | null>(null);
  const [devPlan, setDevPlan] = useState<DevelopmentPlan | null>(null);
  const [prototype, setPrototype] = useState<PrototypeView | null>(null);
  const [loading, setLoading] = useState<string | null>(null);
  const [expandedSections, setExpandedSections] = useState<Record<string, boolean>>({
    howItWorks: true,
    whyCombination: true,
    targetUsers: false,
    keyFeatures: true,
    innovation: false,
    scores: true,
  });

  const result = currentResult;
  if (!result) return null;

  const isSaved = savedIdeas.some((i) => i.id === result.id);
  const isFavorite = result.favorite;

  const toggleSection = (key: string) => {
    setExpandedSections((prev) => ({ ...prev, [key]: !prev[key] }));
  };

  const handleSave = () => {
    addSavedIdea(result);
  };

  const handleCopy = useCallback(() => {
    const text = `${result.inventionName}\n\n${result.description}\n\nInnovation Score: ${result.scores.overall}/100`;
    navigator.clipboard.writeText(text);
  }, [result]);

  const handleExportTxt = useCallback(() => {
    const content = `
IdeaFusion - Invention Concept
==============================

Invention: ${result.inventionName}
Tagline: ${result.tagline}
Category: ${result.category}

Original Ideas: ${result.ideaA} + ${result.ideaB}
${result.targetArea ? `Target Area: ${result.targetArea}` : ''}

DESCRIPTION
${result.description}

HOW IT WORKS
${result.howItWorks.map((s, i) => `${i + 1}. ${s}`).join('\n')}

WHY THIS COMBINATION
${result.whyCombination}

TARGET USERS
${result.targetUsers.map((u) => `• ${u}`).join('\n')}

KEY FEATURES
${result.keyFeatures.map((f) => `• ${f}`).join('\n')}

INNOVATION ADVANTAGE
${result.innovationAdvantage}

SCORES
• Originality: ${result.scores.originality}%
• Feasibility: ${result.scores.feasibility}%
• Market Potential: ${result.scores.marketPotential}%
• Social Impact: ${result.scores.socialImpact}%
• Technical Complexity: ${result.scores.technicalComplexity}%
• Overall: ${result.scores.overall}/100

Generated by IdeaFusion
    `.trim();

    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${result.inventionName.replace(/\s+/g, '_')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }, [result]);

  const handleLoadAlternatives = async () => {
    setLoading('alternatives');
    const alts = await generateAlternatives(result.ideaA, result.ideaB);
    setAlternatives(alts);
    setLoading(null);
  };

  const handleImprove = async () => {
    setLoading('improve');
    const imp = await improveIdea(result);
    setImproved(imp);
    setLoading(null);
  };

  const handleDevPlan = async () => {
    setLoading('devPlan');
    const plan = await generateDevelopmentPlan(result);
    setDevPlan(plan);
    setLoading(null);
  };

  const handlePrototype = async () => {
    setLoading('prototype');
    const proto = await generatePrototype(result);
    setPrototype(proto);
    setLoading(null);
  };

  const SectionHeader = ({ title, icon: Icon, sectionKey }: { title: string; icon: React.ElementType; sectionKey: string }) => (
    <button
      onClick={() => toggleSection(sectionKey)}
      className="w-full flex items-center justify-between py-3 group"
    >
      <div className="flex items-center gap-2">
        <Icon size={18} className="text-primary-400" />
        <h3 className="text-lg font-semibold text-white">{title}</h3>
      </div>
      {expandedSections[sectionKey] ? (
        <ChevronUp size={18} className="text-slate-500" />
      ) : (
        <ChevronDown size={18} className="text-slate-500" />
      )}
    </button>
  );

  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 py-8">
      {/* Back & actions */}
      <motion.div
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        className="flex flex-wrap items-center gap-3 mb-8"
      >
        <button onClick={() => setCurrentView('workspace')} className="btn-secondary text-sm px-3 py-2 flex items-center gap-1.5">
          <ArrowLeft size={14} /> Back
        </button>
        <div className="flex-1" />
        <button onClick={handleSave} className={`btn-secondary text-sm px-3 py-2 flex items-center gap-1.5 ${isSaved ? 'text-primary-400 border-primary-500/40' : ''}`}>
          {isSaved ? <BookmarkCheck size={14} /> : <Bookmark size={14} />}
          {isSaved ? 'Saved' : 'Save'}
        </button>
        <button onClick={() => toggleFavorite(result.id)} className={`btn-secondary text-sm px-3 py-2 flex items-center gap-1.5 ${isFavorite ? 'text-red-400 border-red-500/40' : ''}`}>
          <Heart size={14} fill={isFavorite ? 'currentColor' : 'none'} />
        </button>
        <button onClick={handleCopy} className="btn-secondary text-sm px-3 py-2 flex items-center gap-1.5">
          <Copy size={14} /> Copy
        </button>
        <button onClick={handleExportTxt} className="btn-secondary text-sm px-3 py-2 flex items-center gap-1.5">
          <Download size={14} /> Export TXT
        </button>
      </motion.div>

      {/* Header */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <div className="flex items-center gap-2 mb-2">
          <span className="text-xs font-semibold px-2.5 py-1 rounded-full bg-primary-500/20 text-primary-300 uppercase tracking-wider">
            Fusion Result
          </span>
          <span className="text-xs px-2.5 py-1 rounded-full bg-white/5 text-slate-400">
            {result.category}
          </span>
        </div>
        <h1 className="text-2xl sm:text-3xl font-bold text-white mb-2 font-[var(--font-display)]">
          {result.inventionName}
        </h1>
        <p className="text-sm text-slate-400 italic mb-4">{result.tagline}</p>
        <div className="flex items-center gap-3 text-xs text-slate-500">
          <span>{result.ideaA}</span>
          <Zap size={12} className="text-primary-400" />
          <span>{result.ideaB}</span>
          {result.targetArea && (
            <>
              <span>•</span>
              <span>{result.targetArea}</span>
            </>
          )}
        </div>
      </motion.div>

      {/* Scores */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.1 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <SectionHeader title="Innovation Score" icon={Award} sectionKey="scores" />
        <AnimatePresence>
          {expandedSections.scores && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <div className="flex justify-center mb-8 mt-4">
                <OverallScore score={result.scores.overall} />
              </div>
              <div className="grid grid-cols-2 sm:grid-cols-5 gap-6 mb-6">
                <ScoreRing value={result.scores.originality} label="Originality" delay={100} />
                <ScoreRing value={result.scores.feasibility} label="Feasibility" delay={200} />
                <ScoreRing value={result.scores.marketPotential} label="Market Potential" delay={300} />
                <ScoreRing value={result.scores.socialImpact} label="Social Impact" delay={400} />
                <ScoreRing value={result.scores.technicalComplexity} label="Tech Complexity" delay={500} />
              </div>
              <div className="space-y-3 mt-6">
                <ScoreBar value={result.scores.originality} label="Originality" delay={0.2} />
                <ScoreBar value={result.scores.feasibility} label="Feasibility" delay={0.3} />
                <ScoreBar value={result.scores.marketPotential} label="Market Potential" delay={0.4} />
                <ScoreBar value={result.scores.socialImpact} label="Social Impact" delay={0.5} />
                <ScoreBar value={result.scores.technicalComplexity} label="Technical Complexity" delay={0.6} />
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Description */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.15 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <div className="flex items-center gap-2 mb-4">
          <Lightbulb size={18} className="text-primary-400" />
          <h3 className="text-lg font-semibold text-white">What Is It?</h3>
        </div>
        <p className="text-slate-300 leading-relaxed">{result.description}</p>
      </motion.div>

      {/* How it works */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.2 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <SectionHeader title="How It Works" icon={Cpu} sectionKey="howItWorks" />
        <AnimatePresence>
          {expandedSections.howItWorks && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <ol className="space-y-3 mt-4">
                {result.howItWorks.map((step, i) => (
                  <li key={i} className="flex gap-3">
                    <span className="flex-shrink-0 w-7 h-7 rounded-lg bg-primary-500/10 flex items-center justify-center text-xs font-bold text-primary-400">
                      {i + 1}
                    </span>
                    <span className="text-slate-300 text-sm pt-1">{step}</span>
                  </li>
                ))}
              </ol>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Why this combination */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.25 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <SectionHeader title="Why This Combination?" icon={Sparkles} sectionKey="whyCombination" />
        <AnimatePresence>
          {expandedSections.whyCombination && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <p className="text-slate-300 leading-relaxed mt-3">{result.whyCombination}</p>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Target Users */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.3 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <SectionHeader title="Target Users" icon={Users} sectionKey="targetUsers" />
        <AnimatePresence>
          {expandedSections.targetUsers && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <div className="flex flex-wrap gap-2 mt-3">
                {result.targetUsers.map((user, i) => (
                  <span key={i} className="px-3 py-1.5 rounded-lg bg-white/5 text-sm text-slate-300">
                    {user}
                  </span>
                ))}
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Key Features */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.35 }}
        className="glass-card p-6 sm:p-8 mb-6"
      >
        <SectionHeader title="Key Features" icon={Target} sectionKey="keyFeatures" />
        <AnimatePresence>
          {expandedSections.keyFeatures && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 mt-3">
                {result.keyFeatures.map((feature, i) => (
                  <div key={i} className="flex items-start gap-2 p-2 rounded-lg hover:bg-white/[0.02] transition-colors">
                    <div className="w-1.5 h-1.5 rounded-full bg-primary-400 mt-2 flex-shrink-0" />
                    <span className="text-sm text-slate-300">{feature}</span>
                  </div>
                ))}
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Innovation Advantage */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.4 }}
        className="glass-card p-6 sm:p-8 mb-8"
      >
        <SectionHeader title="Innovation Advantage" icon={Award} sectionKey="innovation" />
        <AnimatePresence>
          {expandedSections.innovation && (
            <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: 'auto', opacity: 1 }} exit={{ height: 0, opacity: 0 }}>
              <p className="text-slate-300 leading-relaxed mt-3">{result.innovationAdvantage}</p>
            </motion.div>
          )}
        </AnimatePresence>
      </motion.div>

      {/* Action buttons */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4 mb-8">
        <button
          onClick={handleImprove}
          disabled={loading === 'improve'}
          className="btn-primary py-3 flex items-center justify-center gap-2 text-sm disabled:opacity-50"
        >
          <Sparkles size={16} />
          {loading === 'improve' ? 'Improving…' : '✨ Improve This Idea'}
        </button>
        <button
          onClick={handleDevPlan}
          disabled={loading === 'devPlan'}
          className="btn-secondary py-3 flex items-center justify-center gap-2 text-sm disabled:opacity-50"
        >
          <Wrench size={16} />
          {loading === 'devPlan' ? 'Generating…' : 'Develop This Idea'}
        </button>
        <button
          onClick={handlePrototype}
          disabled={loading === 'prototype'}
          className="btn-secondary py-3 flex items-center justify-center gap-2 text-sm disabled:opacity-50"
        >
          <FlaskConical size={16} />
          {loading === 'prototype' ? 'Generating…' : 'Prototype View'}
        </button>
        <button
          onClick={handleLoadAlternatives}
          disabled={loading === 'alternatives'}
          className="btn-secondary py-3 flex items-center justify-center gap-2 text-sm disabled:opacity-50"
        >
          <Eye size={16} />
          {loading === 'alternatives' ? 'Loading…' : 'Other Fusions'}
        </button>
      </div>

      {/* Improved idea */}
      <AnimatePresence>
        {improved && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
            className="glass-card p-6 sm:p-8 mb-6"
          >
            <h3 className="text-lg font-semibold text-white mb-4 flex items-center gap-2">
              <Sparkles size={18} className="text-accent-400" /> Improved Version
            </h3>
            <p className="text-slate-300 text-sm leading-relaxed mb-4">{improved.improvedVersion}</p>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {[
                { title: 'Additional Features', items: improved.additionalFeatures },
                { title: 'Cost Reduction Ideas', items: improved.costReductionIdeas },
                { title: 'Sustainability', items: improved.sustainabilityImprovements },
                { title: 'Tech Upgrades', items: improved.technologyUpgrades },
                { title: 'UX Improvements', items: improved.uxImprovements },
                { title: 'Possible Problems', items: improved.possibleProblems },
                { title: 'Solutions', items: improved.solutions },
              ].map((section) => (
                <div key={section.title} className="p-3 rounded-xl bg-white/[0.02]">
                  <h4 className="text-sm font-semibold text-primary-300 mb-2">{section.title}</h4>
                  <ul className="space-y-1">
                    {section.items.map((item, i) => (
                      <li key={i} className="text-xs text-slate-400 flex items-start gap-1.5">
                        <span className="w-1 h-1 rounded-full bg-primary-500 mt-1.5 flex-shrink-0" />
                        {item}
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Development Plan */}
      <AnimatePresence>
        {devPlan && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
            className="glass-card p-6 sm:p-8 mb-6"
          >
            <h3 className="text-lg font-semibold text-white mb-6 flex items-center gap-2">
              <Wrench size={18} className="text-primary-400" /> Development Plan
            </h3>

            <div className="space-y-5">
              {[
                { label: '1. Problem Statement', content: devPlan.problemStatement },
                { label: '2. Proposed Solution', content: devPlan.proposedSolution },
                { label: '3. Target Users', content: devPlan.targetUsers },
                { label: '9. System Architecture', content: devPlan.systemArchitecture },
                { label: '10. Estimated Cost', content: devPlan.estimatedCost },
                { label: '11. Timeline', content: devPlan.developmentTimeline },
                { label: '14. Business Potential', content: devPlan.businessPotential },
              ].map((item) => (
                <div key={item.label}>
                  <h4 className="text-sm font-semibold text-primary-300 mb-1">{item.label}</h4>
                  <p className="text-sm text-slate-300">{item.content}</p>
                </div>
              ))}

              {[
                { label: '4. Core Features', items: devPlan.coreFeatures },
                { label: '5. Required Technologies', items: devPlan.requiredTechnologies },
                { label: '6. Hardware Requirements', items: devPlan.hardwareRequirements },
                { label: '7. Software Requirements', items: devPlan.softwareRequirements },
                { label: '8. Working Process', items: devPlan.workingProcess },
                { label: '12. Challenges', items: devPlan.possibleChallenges },
                { label: '13. Future Improvements', items: devPlan.futureImprovements },
              ].map((section) => (
                <div key={section.label}>
                  <h4 className="text-sm font-semibold text-primary-300 mb-2">{section.label}</h4>
                  <ul className="space-y-1">
                    {section.items.map((item, i) => (
                      <li key={i} className="text-sm text-slate-400 flex items-start gap-2">
                        <span className="w-1.5 h-1.5 rounded-full bg-primary-400 mt-1.5 flex-shrink-0" />
                        {item}
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Prototype */}
      <AnimatePresence>
        {prototype && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
            className="glass-card p-6 sm:p-8 mb-6"
          >
            <h3 className="text-lg font-semibold text-white mb-6 flex items-center gap-2">
              <FlaskConical size={18} className="text-accent-400" /> Prototype Concept
            </h3>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
              <div className="p-4 rounded-xl bg-white/[0.02]">
                <h4 className="text-sm font-semibold text-primary-300 mb-2">Components</h4>
                <ul className="space-y-1">
                  {prototype.components.map((c, i) => (
                    <li key={i} className="text-xs text-slate-400 flex gap-1.5 items-start">
                      <span className="w-1 h-1 rounded-full bg-primary-400 mt-1.5 flex-shrink-0" />
                      {c}
                    </li>
                  ))}
                </ul>
              </div>
              <div className="space-y-3">
                <div className="p-3 rounded-xl bg-white/[0.02]">
                  <h4 className="text-xs font-semibold text-primary-300 mb-1">Input</h4>
                  <p className="text-xs text-slate-400">{prototype.input}</p>
                </div>
                <div className="p-3 rounded-xl bg-white/[0.02]">
                  <h4 className="text-xs font-semibold text-primary-300 mb-1">Processing</h4>
                  <p className="text-xs text-slate-400">{prototype.processing}</p>
                </div>
                <div className="p-3 rounded-xl bg-white/[0.02]">
                  <h4 className="text-xs font-semibold text-primary-300 mb-1">Output</h4>
                  <p className="text-xs text-slate-400">{prototype.output}</p>
                </div>
              </div>
            </div>

            {/* System flow */}
            <div className="flex flex-col items-center gap-2">
              <h4 className="text-sm font-semibold text-slate-300 mb-2">System Flow</h4>
              {prototype.systemFlow.map((step, i) => (
                <div key={i} className="flex flex-col items-center">
                  <div className="px-4 py-2 rounded-lg bg-gradient-to-r from-primary-500/10 to-accent-500/10 border border-primary-500/20 text-sm text-white font-medium">
                    {step}
                  </div>
                  {i < prototype.systemFlow.length - 1 && (
                    <div className="w-px h-4 bg-primary-500/30" />
                  )}
                </div>
              ))}
            </div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Alternatives */}
      <AnimatePresence>
        {alternatives.length > 0 && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
            className="mb-6"
          >
            <h3 className="text-lg font-semibold text-white mb-4">Other Possible Fusions</h3>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {alternatives.map((alt, i) => (
                <motion.div
                  key={i}
                  initial={{ opacity: 0, y: 10 }}
                  animate={{ opacity: 1, y: 0 }}
                  transition={{ delay: i * 0.1 }}
                  className="glass-card p-5"
                >
                  <span className="text-xs px-2 py-0.5 rounded-full bg-white/5 text-slate-400">{alt.category}</span>
                  <h4 className="text-base font-semibold text-white mt-2 mb-1">{alt.inventionName}</h4>
                  <p className="text-xs text-slate-400 mb-3 line-clamp-2">{alt.shortDescription}</p>
                  <div className="flex items-center gap-4 text-xs">
                    <span className="text-primary-400">Innovation: {alt.innovationScore}%</span>
                    <span className="text-accent-400">Feasibility: {alt.feasibilityScore}%</span>
                  </div>
                </motion.div>
              ))}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
